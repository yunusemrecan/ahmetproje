LANGUAGES = {"tr": TR, "en": EN}
_current: dict[str, str] = TR


def set_language(code: str) -> None:
    global _current
    _current = LANGUAGES.get(code, EN)


def current_language() -> str:
    return "tr" if _current is TR else "en"


def tr(key: str, **kwargs: object) -> str:
    text = _current.get(key) or TR.get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text
